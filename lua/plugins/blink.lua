-- ============================================================================
-- BLINK.CMP
-- ============================================================================

local blink = require('blink.cmp')

-- ============================================================================
-- CONSTRUCTION DU MOTEUR FUZZY NATIF
-- ============================================================================

if not blink.library_available() then
  blink.build():pwait()
end

-- ============================================================================
-- CONFIGURATION
-- ============================================================================

blink.setup({
  -- --------------------------------------------------------------------------
  -- RACCOURCIS
  -- --------------------------------------------------------------------------

  keymap = {
    -- Accepter la suggestion
    ['<CR>'] = { 'accept', 'fallback' },

    -- Naviguer dans les suggestions
    ['<Tab>'] = { 'select_next', 'fallback' },
    ['<S-Tab>'] = { 'select_prev', 'fallback' },

    -- Fermer le menu
    ['<Esc>'] = { 'cancel', 'fallback' },

    -- Ouvrir manuellement la complétion
    ['<C-Space>'] = {
      'show',
      'show_documentation',
      'hide',
    },
  },

  -- --------------------------------------------------------------------------
  -- ACCEPTATION DES SUGGESTIONS
  -- --------------------------------------------------------------------------

  completion = {
    accept = {
      auto_brackets = {
        enabled = true,
      },
    },
  },

  -- --------------------------------------------------------------------------
  -- SOURCES
  -- --------------------------------------------------------------------------

  sources = {
    default = {
      'lsp',
      'path',
      'snippets',
      'buffer',
    },
  },

  -- --------------------------------------------------------------------------
  -- RECHERCHE FLOUE
  -- --------------------------------------------------------------------------

  fuzzy = {
    implementation = 'rust',
  },
})
